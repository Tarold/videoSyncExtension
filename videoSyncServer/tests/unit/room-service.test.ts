import { beforeEach, describe, expect, it } from 'vitest';
import { ERRORS, RoomService } from '../../src/domain/room-service.js';
import { MemoryRoomStore } from '../../src/persistence/memory-store.js';
import type { RoomStore } from '../../src/persistence/room-store.js';
import { FakeConnection, sequence, silentLogger } from '../helpers.js';

const NOW = 1_700_000_000_000;

describe('RoomService', () => {
  let store: MemoryRoomStore;
  let service: RoomService;

  beforeEach(() => {
    store = new MemoryRoomStore();
    service = new RoomService(store, silentLogger, {
      random: sequence(0.5, 0, 0.1, 0.2),
      now: () => NOW,
    });
  });

  async function roomWith(...userIds: string[]) {
    const [ownerId = 'owner', ...others] = userIds;
    const owner = new FakeConnection();
    const room = await service.createRoom(ownerId, owner, 'https://v.example');
    if (!room) throw new Error('room not created');
    const connections = new Map([[ownerId, owner]]);
    for (const id of others) {
      const connection = new FakeConnection();
      await service.joinRoom(room.id, id, connection);
      connections.set(id, connection);
    }
    for (const c of connections.values()) c.clear();
    return {
      room,
      conn: (id: string) => connections.get(id) ?? new FakeConnection(),
    };
  }

  describe('createRoom', () => {
    it('creates a room with runtime defaults and makes the creator owner', async () => {
      const owner = new FakeConnection();
      const room = await service.createRoom(
        'alice',
        owner,
        'https://v.example',
      );

      expect(room?.id).toBe('550');
      expect(owner.messages).toEqual([
        {
          action: 'joined',
          roomId: '550',
          roomName: expect.any(String) as string,
          isOwner: true,
          settings: { democracy: true, autoSyncUrl: false },
          videoUrl: 'https://v.example',
        },
        {
          action: 'room-meta-update',
          users: ['alice'],
          ownerId: 'alice',
          hosts: ['alice'],
          settings: { democracy: true, autoSyncUrl: false },
        },
      ]);
      expect(await store.findRoom('550')).toMatchObject({
        ownerId: 'alice',
        settings: { democracy: true, autoSyncUrl: false },
        hosts: ['alice'],
      });
    });

    it('skips codes that are already taken in storage', async () => {
      await store.createRoom({
        id: '550',
        name: 'x',
        ownerId: 'someone',
        settings: { democracy: true, autoSyncUrl: false },
      });
      const room = await service.createRoom(
        'alice',
        new FakeConnection(),
        undefined,
      );
      expect(room?.id).not.toBe('550');
    });

    it('never hands out the same code to concurrent creates', async () => {
      service = new RoomService(store, silentLogger, { random: () => 0.5 });
      const [a, b] = await Promise.all([
        service.createRoom('a', new FakeConnection(), undefined),
        service.createRoom('b', new FakeConnection(), undefined),
      ]);
      expect(a?.id).toBe('550');
      expect(b).toBeNull(); // only one code is ever generated by this random source
    });

    it('reports an internal error when storage fails', async () => {
      const failing: RoomStore = Object.assign(new MemoryRoomStore(), {
        createRoom: () => Promise.reject(new Error('db down')),
      });
      service = new RoomService(failing, silentLogger);
      const connection = new FakeConnection();
      expect(await service.createRoom('a', connection, undefined)).toBeNull();
      expect(connection.last()).toEqual({
        action: 'error',
        message: ERRORS.internal,
      });
      expect(service.roomCount).toBe(0);
    });
  });

  describe('joinRoom', () => {
    it('sends joined to the newcomer and the member list to everyone', async () => {
      const { room, conn } = await roomWith('alice');
      const bob = new FakeConnection();
      await service.joinRoom(room.id, 'bob', bob);

      expect(bob.messages[0]).toMatchObject({
        action: 'joined',
        roomId: room.id,
        isOwner: false,
      });
      const meta = {
        action: 'room-meta-update',
        users: ['alice', 'bob'],
        ownerId: 'alice',
      };
      expect(bob.last()).toMatchObject(meta);
      expect(conn('alice').last()).toMatchObject(meta);
    });

    it('returns Room not found for unknown codes', async () => {
      const connection = new FakeConnection();
      expect(await service.joinRoom('999', 'bob', connection)).toBeNull();
      expect(connection.messages).toEqual([
        { action: 'error', message: 'Room not found' },
      ]);
    });

    it('restores a persisted room that is not live (e.g. after a restart)', async () => {
      const { room } = await roomWith('alice', 'bob');
      await service.updateSettings(
        room.id,
        'alice',
        { democracy: false },
        new FakeConnection(),
      );

      const restarted = new RoomService(store, silentLogger);
      const alice = new FakeConnection();
      const restored = await restarted.joinRoom(room.id, 'alice', alice);

      expect(restored).toMatchObject({
        id: room.id,
        name: room.name,
        ownerId: 'alice',
        hosts: ['alice'],
        settings: { democracy: false, autoSyncUrl: false },
        videoUrl: null,
      });
      expect(alice.messages[0]).toMatchObject({
        action: 'joined',
        isOwner: true,
      });
    });
  });

  describe('leaveRoom', () => {
    it('deletes the room when the last member leaves', async () => {
      const { room } = await roomWith('alice');
      await service.leaveRoom(room.id, 'alice');
      expect(service.getRoom(room.id)).toBeUndefined();
      expect(await store.roomExists(room.id)).toBe(false);
    });

    it('transfers ownership to the next member when the owner leaves', async () => {
      const { room, conn } = await roomWith('alice', 'bob', 'carol');
      await service.leaveRoom(room.id, 'alice');

      expect(conn('bob').last()).toEqual({
        action: 'room-meta-update',
        users: ['bob', 'carol'],
        ownerId: 'bob',
        hosts: ['alice', 'bob'],
        settings: { democracy: true, autoSyncUrl: false },
      });
      expect((await store.findRoom(room.id))?.ownerId).toBe('bob');
    });

    it('ignores a stale socket closing after the user reconnected', async () => {
      const { room } = await roomWith('alice', 'bob');
      const staleBob = room.members.get('bob');
      const freshBob = new FakeConnection();
      await service.joinRoom(room.id, 'bob', freshBob);

      await service.leaveRoom(room.id, 'bob', staleBob);

      expect(room.members.get('bob')).toBe(freshBob);
    });
  });

  describe('videoUpdate', () => {
    const playing = { playerStatus: 'PLAYING', second: 12, timestamp: NOW };

    it('relays state to everyone except the sender', async () => {
      const { room, conn } = await roomWith('alice', 'bob');
      service.videoUpdate(
        room.id,
        'bob',
        { playerState: playing },
        conn('bob'),
      );

      expect(conn('bob').messages).toEqual([]);
      expect(conn('alice').last()).toEqual({
        action: 'sync-video',
        state: playing,
        videoUrl: 'https://v.example',
        initiatorId: 'bob',
      });
    });

    it('silently ignores non-hosts when democracy is off', async () => {
      const { room, conn } = await roomWith('alice', 'bob');
      await service.updateSettings(
        room.id,
        'alice',
        { democracy: false },
        conn('alice'),
      );
      conn('alice').clear();

      const applied = service.videoUpdate(
        room.id,
        'bob',
        { playerState: playing },
        conn('bob'),
      );

      expect(applied).toBe(false);
      expect(conn('alice').messages).toEqual([]);
      expect(room.playerState.playerStatus).toBe('INIT');
    });

    it('lets hosts control playback when democracy is off', async () => {
      const { room, conn } = await roomWith('alice', 'bob');
      await service.updateSettings(
        room.id,
        'alice',
        { democracy: false },
        conn('alice'),
      );
      expect(
        service.videoUpdate(
          room.id,
          'alice',
          { playerState: playing },
          conn('alice'),
        ),
      ).toBe(true);
    });
  });

  describe('getState', () => {
    it('replies only to the requester with initiator "server"', async () => {
      const { room, conn } = await roomWith('alice', 'bob');
      service.getState(room.id, conn('bob'));
      expect(conn('bob').messages).toEqual([
        {
          action: 'sync-video',
          state: { playerStatus: 'INIT', second: 0, timestamp: NOW },
          videoUrl: 'https://v.example',
          initiatorId: 'server',
        },
      ]);
      expect(conn('alice').messages).toEqual([]);
    });
  });

  describe('updateSettings', () => {
    it('lets the owner change settings and broadcasts them', async () => {
      const { room, conn } = await roomWith('alice', 'bob');
      await service.updateSettings(
        room.id,
        'alice',
        { democracy: false },
        conn('alice'),
      );

      expect(conn('bob').last()).toMatchObject({
        action: 'room-meta-update',
        settings: { democracy: false, autoSyncUrl: false },
      });
      expect((await store.findRoom(room.id))?.settings.democracy).toBe(false);
    });

    it('rejects non-owners', async () => {
      const { room, conn } = await roomWith('alice', 'bob');
      await service.updateSettings(
        room.id,
        'bob',
        { democracy: false },
        conn('bob'),
      );

      expect(conn('bob').messages).toEqual([
        { action: 'error', message: 'Only room owner can change settings' },
      ]);
      expect(room.settings.democracy).toBe(true);
    });

    it('returns Room not found for unknown rooms', async () => {
      const connection = new FakeConnection();
      await service.updateSettings(
        '999',
        'alice',
        { democracy: false },
        connection,
      );
      expect(connection.messages).toEqual([
        { action: 'error', message: 'Room not found' },
      ]);
    });
  });
});
